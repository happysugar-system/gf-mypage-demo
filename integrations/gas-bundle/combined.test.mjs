import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const source=fs.readFileSync(new URL('./GF_DocumentCombined.gs',import.meta.url),'utf8');
const c=vm.createContext({ContentService:{MimeType:{JSON:'json'},createTextOutput:s=>({setMimeType:()=>JSON.parse(s)})}});
vm.runInContext(source,c);
assert.equal(c.GF_DocumentCombinedRoute_({parameter:{}}),null);
assert.equal(c.GF_DocumentCombinedRoute_({parameter:{gf_document_bridge:'unknown'}}).error,'unknown_bridge');
c.GF_DocumentResubmissionRoute_=()=> 'resubmission';
c.GF_DocumentApprovalRoute_=()=> 'approval';
assert.equal(c.GF_DocumentCombinedRoute_({parameter:{gf_document_bridge:'resubmission_v1'}}),'resubmission');
assert.equal(c.GF_DocumentCombinedRoute_({parameter:{gf_document_bridge:'approval_v1'}}),'approval');
console.log('Combined router checks passed');

const required=['受付番号','確認DriverID','契約状況','免許証PDF','住民票PDF','書類状態','書類フォルダ','免許証確認','住民票確認'];
let headers=[...required.reverse(),'追加列','備考'];
const sheet={getLastColumn:()=>headers.length,getRange:()=>({getDisplayValues:()=>[headers]})};
let target='test-book';
c.GF215_BOOK_ID='test-book';
c.PropertiesService={getScriptProperties:()=>({getProperty:()=>target})};
c.SpreadsheetApp={openById:id=>{assert.equal(id,'test-book');return {getSheetByName:()=>sheet}}};
assert.equal(c.GF_DocumentReceiptSheet_(),sheet);
headers.push('受付番号');
assert.throws(()=>c.GF_DocumentReceiptSheet_(),/receipt_headers_invalid/);
headers.pop();headers=headers.filter(x=>x!=='住民票確認');
assert.throws(()=>c.GF_DocumentReceiptSheet_(),/receipt_headers_invalid/);
target='wrong-book';
assert.throws(()=>c.GF_DocumentReceiptSheet_(),/sheet_target_not_verified/);
console.log('Document schema checks passed');
